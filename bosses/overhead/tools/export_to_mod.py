# ---------------- block & item textures ----------------
def tile16(mat, seed=0):
    atlas, _ = texture.build(seed=11)
    ox, oy = texture.tile_origin(mat)
    rng = np.random.default_rng(seed)
    dx, dy = rng.integers(0, 48, 2)
    return atlas.crop((ox + dx, oy + dy, ox + dx + 16, oy + dy + 16))


def frame(a, color, w=1):
    a[:w, :, :3] = color
    a[-w:, :, :3] = color
    a[:, :w, :3] = color
    a[:, -w:, :3] = color
    return a


