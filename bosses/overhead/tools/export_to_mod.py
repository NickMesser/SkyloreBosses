# ---------------- sounds ----------------
def sound_files(ids, synth=True):
    sdir = mk(ASSETS, "sounds", BOSS)
    path = os.path.join(ASSETS, "sounds.json")
    j = json.load(open(path)) if os.path.exists(path) else {}
    j = {k: v for k, v in j.items() if not k.startswith(BOSS + ".")}
    for sid in ids:
        fname = sid.replace(".", "_")
        if synth:
            sounds.write(sid, os.path.join(sdir, f"{fname}.ogg"))
        entry = {"subtitle": f"subtitles.{NS}.{BOSS}.{sid}", "sounds": [{"name": f"{NS}:{BOSS}/{fname}"}]}
        if sid.split(".")[0] in ("carpet", "rearm", "lockdown", "victory", "howitzer", "shell", "pylon", "power", "death"):
            entry["sounds"][0]["attenuation_distance"] = 96
        j[f"{BOSS}.{sid}"] = entry
    with open(path, "w") as f:
        json.dump(dict(sorted(j.items())), f, indent=2)
    with open(SOUND_IDS, "w") as f:
        f.write("\n".join(ids))


def sound_ids_java(ids):
    body = ",\n            ".join(f'"{s}"' for s in ids)
    src = f"""package net.teamaof.skylorebosses.bosses.overhead;

/** GENERATED by bosses/overhead/tools/export_to_mod.py: Overhead sound ids (registered as skylore_bosses:overhead.<id>). */
public final class OverheadSoundIds {{
    public static final String[] ALL = {{
            {body}
    }};

    private OverheadSoundIds() {{}}
}}
"""
    with open(os.path.join(mk(JAVA), "OverheadSoundIds.java"), "w") as f:
        f.write(src)


