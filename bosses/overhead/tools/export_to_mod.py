def mk(*p):
    d = os.path.join(*p)
    os.makedirs(d, exist_ok=True)
    return d


def copy_models():
    for kind, names in (("entity", ENTITY_MODELS), ("block", BLOCK_MODELS)):
        for n in names:
            src = os.path.join(boss_env.MODELS, n)
            shutil.copy(os.path.join(src, f"{n}.geo.json"), os.path.join(mk(ASSETS, "geo", kind, BOSS), f"{n}.geo.json"))
            shutil.copy(os.path.join(src, f"{n}.animation.json"), os.path.join(mk(ASSETS, "animations", kind, BOSS), f"{n}.animation.json"))
            shutil.copy(os.path.join(src, f"{n}.png"), os.path.join(mk(ASSETS, "textures", kind, BOSS), f"{n}.png"))
            shutil.copy(os.path.join(src, f"{n}_glowmask.png"), os.path.join(mk(ASSETS, "textures", kind, BOSS), f"{n}_glowmask.png"))


def _pairs(locs):
    return [f'"{l["name"]}", new float[]{{{l["pos"][0]:.2f}f, {l["pos"][1]:.2f}f, {l["pos"][2]:.2f}f}}' for l in locs]


def locators_java():
    lines, sound_ids = [], set()
    for n in ENTITY_MODELS + BLOCK_MODELS:
        m = FACTORIES[n]()
        for a in m.anims:
            for s in a["sounds"]:
                sound_ids.add(s["effect"].split(":", 1)[1])
        lines.append(f'        ModelLocators.register("{n}", Map.ofEntries({", ".join("Map.entry(" + e + ")" for e in _pairs(m.locators))}));')
    src = f"""package net.teamaof.skylorebosses.bosses.overhead;

import java.util.Map;
import net.teamaof.skylorebosses.core.fx.ModelLocators;

/** GENERATED by bosses/overhead/tools/export_to_mod.py from the Blockbench specs. Rest-pose locators in model pixels. */
public final class OverheadLocators {{
    private OverheadLocators() {{}}

    public static void register() {{
{chr(10).join(lines)}
    }}
}}
"""
    with open(os.path.join(mk(JAVA), "OverheadLocators.java"), "w") as f:
        f.write(src)
    return sorted(sound_ids | set(EXTRA_SOUNDS))


